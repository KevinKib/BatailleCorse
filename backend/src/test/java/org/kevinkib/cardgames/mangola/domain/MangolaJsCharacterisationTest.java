package org.kevinkib.cardgames.mangola.domain;

import org.junit.jupiter.api.Test;
import org.kevinkib.cardgames.game.GameId;
import org.kevinkib.cardgames.game.PlayerId;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Characterisation of the sowing engine against the owner's reference implementation
 * ({@code KevinKib/Ngola}, {@code script/ngola.js}): every line of
 * {@code mangola/js-reference-moves.txt} is a position, a pit and the board, winner and next player the
 * JavaScript produced; the Java aggregate must reproduce them. The file is generated by
 * {@code src/test/resources/mangola/generate-js-reference-moves.js} (command:
 * {@code node generate-js-reference-moves.js <Ngola>/script fixture}, header of the file for the commit
 * of the JS); nothing here runs Node.
 *
 * <p>Lines ending in {@code ENDLESS} are moves where the JS gave up after 100,000 iterations (game over,
 * no winner). The rule differs on purpose: the Java engine refuses such a move
 * ({@link EndlessSowingException}), so only the fact that it is refused is compared.
 *
 * <p>A larger run can be done without committing anything: pass {@code -Dmangola.js.moves=<file>} (same
 * format, e.g. the generator in {@code big} mode) and that file is replayed as well.
 */
class MangolaJsCharacterisationTest {

    private static final String RESOURCE = "/mangola/js-reference-moves.txt";
    private static final PlayerId SEAT_A = new PlayerId(0);
    private static final PlayerId SEAT_B = new PlayerId(1);

    @Test
    void theFixtureReproducesTheJavaScriptMoves() throws IOException {
        Counts counts = replay(readResource());
        assertTrue(counts.finite >= 250, "finite moves replayed: " + counts.finite);
        assertTrue(counts.endless >= 1, "endless moves replayed: " + counts.endless);
        assertTrue(counts.finished >= 1, "moves that ended a game: " + counts.finished);
    }

    @Test
    void anOptionalLargerFileIsReplayedToo() throws IOException {
        String path = System.getProperty("mangola.js.moves");
        if (path == null || path.isBlank()) {
            return;
        }
        Counts counts = replay(Files.readAllLines(Path.of(path), StandardCharsets.UTF_8));
        System.out.println("mangola.js.moves: " + counts.finite + " finite, " + counts.endless + " endless, "
                + counts.finished + " game-ending moves replayed");
    }

    private static List<String> readResource() throws IOException {
        try (InputStream in = MangolaJsCharacterisationTest.class.getResourceAsStream(RESOURCE)) {
            assertTrue(in != null, "missing fixture " + RESOURCE);
            return new String(in.readAllBytes(), StandardCharsets.UTF_8).lines().toList();
        }
    }

    private record Counts(int finite, int endless, int finished) {
    }

    private static Counts replay(List<String> lines) {
        int finite = 0;
        int endless = 0;
        int finished = 0;
        for (String line : lines) {
            if (line.isBlank() || line.startsWith("#")) {
                continue;
            }
            String[] parts = line.split("\\|");
            String[] head = parts[0].trim().split(" ");
            PlayerId mover = head[0].equals("A") ? SEAT_A : SEAT_B;
            PlayerId other = head[0].equals("A") ? SEAT_B : SEAT_A;
            int pit = MangolaGeometry.pit(head[1]);
            Mangola game = Mangola.fromLayout(GameId.generate(), MangolaRules.OWNER, SEAT_A,
                    Boards.of(parts[1]), mover);
            String context = line;
            if (parts[2].trim().equals("ENDLESS")) {
                assertThrows(EndlessSowingException.class, () -> game.sow(mover, pit), context);
                endless++;
                continue;
            }
            try {
                game.sow(mover, pit);
            } catch (MangolaException e) {
                throw new AssertionError("Java refused a move the JS played: " + context, e);
            }
            assertEquals(Boards.of(parts[2]), game.board(), context);
            String winner = parts[3].trim();
            if (winner.equals("-")) {
                assertEquals(MangolaResult.ONGOING, game.result(), context);
                assertEquals(other, game.currentSeat(), context);
            } else {
                assertEquals(MangolaResult.Reason.NO_MOVE, game.result().reason(), context);
                assertEquals(winner.equals("A") ? SEAT_A : SEAT_B, game.result().winner(), context);
                finished++;
            }
            finite++;
        }
        return new Counts(finite, endless, finished);
    }
}
