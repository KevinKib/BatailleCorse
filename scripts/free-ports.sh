#!/bin/sh
# Picks the smallest port offset for which the frontend (5173), backend (8080) and debug (5005) ports are all
# free, and writes a Compose override that publishes the stack on the shifted ports.
#
#   sh scripts/free-ports.sh <ports.yml>      write the override, print the URL and the compose command
#   sh scripts/free-ports.sh --offset-only    print only the offset
#
# Keep <ports.yml> outside the repository (scratchpad). FREE_PORTS_BUSY="5173 8080" replaces the real probe
# (tests). A port held by a container of another stack is seen as busy because Docker publishes it on the host.
set -eu

FRONT=5173
BACK=8080
DEBUG=5005
MAX_OFFSET=50

busy_ports() {
  if [ "${FREE_PORTS_BUSY+set}" = set ]; then
    echo "$FREE_PORTS_BUSY"
  elif command -v netstat >/dev/null 2>&1; then
    netstat -an 2>/dev/null | tr -s ' ' '\n' | sed -n 's/.*:\([0-9][0-9]*\)$/\1/p' | sort -u
  else
    ss -ltn 2>/dev/null | tr -s ' ' '\n' | sed -n 's/.*:\([0-9][0-9]*\)$/\1/p' | sort -u
  fi
}

BUSY=" $(busy_ports | tr '\n' ' ') "

is_busy() { case "$BUSY" in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

offset=0
while [ "$offset" -le "$MAX_OFFSET" ]; do
  if ! is_busy $((FRONT + offset)) && ! is_busy $((BACK + offset)) && ! is_busy $((DEBUG + offset)); then
    break
  fi
  offset=$((offset + 1))
done
if [ "$offset" -gt "$MAX_OFFSET" ]; then
  echo "No free port triple within +$MAX_OFFSET of $FRONT/$BACK/$DEBUG." >&2
  exit 1
fi

if [ "${1:-}" = "--offset-only" ]; then
  echo "$offset"
  exit 0
fi

target="${1:-}"
if [ -z "$target" ]; then
  echo "Usage: free-ports.sh <ports.yml> | --offset-only" >&2
  exit 2
fi

front=$((FRONT + offset))
back=$((BACK + offset))
debug=$((DEBUG + offset))
cat > "$target" <<EOF
# Generated by scripts/free-ports.sh (offset +$offset).
services:
  backend:
    ports: !override ["$back:8080", "$debug:5005"]
  frontend:
    ports: !override ["$front:5173"]
    environment:
      - VITE_HMR_CLIENT_PORT=$front
EOF

echo "Offset +$offset: frontend $front, backend $back, debug $debug."
echo "URL: http://localhost:$front"
echo "Start: docker compose -p bc-<subject> -f docker-compose.e2e.yml -f $target up --build -d --wait"
echo "Cypress: npx cypress run --config baseUrl=http://localhost:$front"
